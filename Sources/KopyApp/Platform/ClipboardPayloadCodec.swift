import AppKit
import ImageIO
import KopyCore
import UniformTypeIdentifiers

@MainActor
enum ClipboardPayloadCodec {
    static let ownDrag = NSPasteboard.PasteboardType("dev.kopy.local-drag")
    static let internalDrag = NSPasteboard.PasteboardType("com.kopy.clipboard-item")
    private static let urlTitle = NSPasteboard.PasteboardType("public.url-name")
    private static let legacyFilenames = NSPasteboard.PasteboardType("NSFilenamesPboardType")
    static let imageTypes = [UTType.png, .tiff, .jpeg, .gif, .webP, .heic, .bmp].map {
        NSPasteboard.PasteboardType($0.identifier)
    }
    static let supportedDropTypes = [.fileURL, legacyFilenames, .URL, .string, .tabularText, .html, .rtf] + imageTypes
    nonisolated static let imageByteLimit = 32 * 1024 * 1024
    private static let richByteLimit = 1024 * 1024
    private static let textCharacterLimit = 500_000
    private static let excludedTypes = Set([
        "org.nspasteboard.concealedtype",
        "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype",
        "com.agilebits.onepassword",
        "com.bitwarden.concealed",
        "com.apple.is-sensitive",
        "com.apple.pasteboard.concealed",
        "clipboardviewerignore",
        "clipboard viewer ignore",
        "excludeclipboardcontentfrommonitorprocessing",
        "keepassclipformat"
    ])

    static func isPrivate(_ pasteboard: NSPasteboard) -> Bool {
        pasteboard.types?.contains { excludedTypes.contains($0.rawValue.lowercased()) } == true
    }

    static func files(from pasteboard: NSPasteboard) -> [ClipboardMember] {
        if pasteboard.types?.contains(.fileURL) == true {
            let urls = pasteboard.readObjects(
                forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]
            )?.compactMap { $0 as? URL } ?? []
            if !urls.isEmpty { return urls.compactMap(fileMember) }
        }
        if let paths = pasteboard.propertyList(forType: legacyFilenames) as? [String] {
            let members = paths.filter { $0.hasPrefix("/") }.compactMap { path in
                fileMember(URL(fileURLWithPath: path))
            }
            if !members.isEmpty { return members }
        }
        let possibleFile = pasteboard.string(forType: .URL) ?? pasteboard.string(forType: .string)
        if let text = possibleFile?.trimmingCharacters(in: .whitespacesAndNewlines),
           text.lowercased().hasPrefix("file://"), let url = URL(string: text),
           !text.contains(where: \.isNewline), let member = fileMember(url) {
            return [member]
        }
        return []
    }

    private static func fileMember(_ url: URL) -> ClipboardMember? {
        guard url.isFileURL, url.host() == nil || url.host()?.isEmpty == true || url.host() == "localhost",
              let resources = try? url.resourceValues(forKeys: [.isDirectoryKey, .fileSizeKey]),
              let isDirectory = resources.isDirectory else { return nil }
        let bookmark = try? url.bookmarkData(options: .minimalBookmark, includingResourceValuesForKeys: nil, relativeTo: nil)
        return .file(ClipboardFile(
            url: url.standardizedFileURL, size: resources.fileSize, isDirectory: isDirectory, bookmark: bookmark
        ))
    }


    static func nonFilePayload(from pasteboard: NSPasteboard) -> ClipboardPayload? {
        let boardItems = pasteboard.pasteboardItems ?? []
        let fetched = boardItems.compactMap(payload(from:))
        let images = fetched.compactMap { payload -> ClipboardImage? in
            if case .image(let image) = payload { return image }
            return nil
        }
        if images.count > 1 && images.count == fetched.count { return .images(images) }
        return fetched.first
    }

    nonisolated static func image(
        _ data: Data, name: String? = nil, source origin: ClipboardImage.Source = .image
    ) -> ClipboardImage? {
        guard !data.isEmpty, data.count <= imageByteLimit,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let identifier = CGImageSourceGetType(source) as String?,
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              (1...20_000).contains(width), (1...20_000).contains(height),
              width * height <= 100_000_000 else { return nil }
        return ClipboardImage(data: data, typeIdentifier: identifier, name: name, width: width, height: height, source: origin)
    }

    private static func payload(from item: NSPasteboardItem) -> ClipboardPayload? {
        guard !item.types.contains(where: { excludedTypes.contains($0.rawValue.lowercased()) }) else { return nil }

        let plain = item.string(forType: .string)
        let address = item.string(forType: .URL).flatMap { ClipboardText($0).webURL == nil ? nil : $0 }
        let explicitText = item.string(forType: .tabularText) ?? address ?? plain
        let oversizedTable = explicitText.map(ClipboardMarkup.isLargeTable) ?? false
        let html = oversizedTable ? nil : boundedData(for: .html, in: item, limit: ClipboardMarkup.htmlLimit)
        let rtf = oversizedTable ? nil : boundedData(for: .rtf, in: item, limit: richByteLimit)
        let htmlString = html.flatMap { String(data: $0, encoding: .utf8) }
        let string = explicitText ?? rtf.flatMap { NSAttributedString(rtf: $0, documentAttributes: nil)?.string }
            ?? htmlString.map(ClipboardMarkup.plainText)
        let text = string.map { value in
            let normalized = value.contains("\t")
                ? value.replacingOccurrences(of: #"[\r\n]+$"#, with: "", options: .regularExpression)
                : value.trimmingCharacters(in: .whitespacesAndNewlines)
            let providedTitle = item.string(forType: urlTitle) ?? htmlString.flatMap { ClipboardMarkup.linkTitle(in: $0, for: normalized) }
                ?? (address == normalized ? plain : nil)
            let title = providedTitle.map { $0.split(whereSeparator: \.isWhitespace).joined(separator: " ") }
                .flatMap { $0.isEmpty || ClipboardText($0).webURL != nil ? nil : String($0.unicodeScalars.prefix(200)) }
            return ClipboardText(String(normalized.prefix(textCharacterLimit)), html: html, rtf: rtf, title: title)
        }

        let hasWords = text?.value.contains(where: { !$0.isWhitespace }) == true
        if hasWords, let text, !favorsImage(text, html: htmlString) { return .text(text) }

        let namedImage = text?.webURL.flatMap { isWebImageURL($0) ? $0.lastPathComponent : nil }
        let webImage = text?.webURL != nil || htmlString?.range(of: #"(?i)^\s*<img\b"#, options: .regularExpression) != nil
        for type in imageTypes where item.types.contains(type) {
            if let data = item.data(forType: type),
               let image = image(data, name: namedImage, source: webImage ? .image : .screenshot) { return .image(image) }
        }
        if hasWords, let text { return .text(text) }
        return nil
    }

    static func isWebImageURL(_ url: URL) -> Bool {
        url.scheme?.lowercased() == "https" && url.host != nil
            && url.user == nil && url.password == nil
            && UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true
    }

    private static func favorsImage(_ text: ClipboardText, html: String?) -> Bool {
        let value = text.value
        if value.utf16.count < 500 && text.webURL != nil { return true }
        if value.wholeMatch(of: #/(?i)<img\b[^>]*>/#) != nil { return true }
        if let html, html.trimmingCharacters(in: .whitespacesAndNewlines).wholeMatch(of: #/(?i)<img\b[^>]*>/#) != nil {
            return true
        }
        guard value.utf16.count <= 200, !value.contains("\t"), !value.contains(where: \.isNewline),
              text.rtf == nil else { return false }
        let prefix = String((html ?? "").prefix(4_096))
        return prefix.firstMatch(of: #/(?i)<(?:table|tr|td|th|html|body|p|pre|code|ul|ol|li)\b|google-sheets|data-sheets|office:spreadsheet/#) == nil
    }

    private static func boundedData(for type: NSPasteboard.PasteboardType, in item: NSPasteboardItem, limit: Int) -> Data? {
        guard item.types.contains(type), let data = item.data(forType: type),
              !data.isEmpty, data.count <= limit else { return nil }
        return data
    }

    static func textItem(_ text: ClipboardText, plain: Bool) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        let isTable = text.value.contains("\t")
        let value = isTable ? ClipboardMarkup.normalizeRows(text.value) : text.value
        item.setString(value, forType: .string)
        guard !plain else { return item }
        if isTable { item.setString(value, forType: .tabularText) }
        if let url = text.webURL {
            item.setString(url.absoluteString, forType: .URL)
            if let title = text.title { item.setString(title, forType: urlTitle) }
        }
        if let html = isTable ? ClipboardMarkup.tableHTML(value, existing: text.html) : text.html {
            item.setData(html, forType: .html)
        }
        if let rtf = text.rtf { item.setData(rtf, forType: .rtf) }
        return item
    }

    static func item(fileURL: URL? = nil, image: ClipboardImage? = nil) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        if let fileURL { item.setString(fileURL.absoluteString, forType: .fileURL) }
        if let image { item.setData(image.data, forType: .init(image.typeIdentifier)) }
        return item
    }
}
